import { chromium } from 'playwright';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
const page=await browser.newPage({viewport:{width:1440,height:980},deviceScaleFactor:2});
await page.addInitScript(()=>{Element.prototype.requestPointerLock=()=>{};Element.prototype.setPointerCapture=()=>{};});
await page.goto(pathToFileURL(resolve('public/woltspace/prototype/index.html')).href);
await page.evaluate(()=>document.fonts.ready);
await page.waitForTimeout(1300);
const form = await page.locator('.ob-inner').boundingBox();
await page.screenshot({path:'public/woltspace/assets/onboarding.png', clip:{x:form.x-24,y:form.y-24,width:form.width+48,height:form.height+48}});
await page.evaluate(()=>{document.getElementById('onboarding').style.display='none';showProjects();});
await page.waitForTimeout(300);
await page.screenshot({path:'public/woltspace/assets/workspace.png'});
await page.evaluate(()=>{document.getElementById('bg-scene').style.display='none';});
await page.screenshot({path:'public/woltspace/assets/workspace-quiet.png'});
await page.evaluate(()=>openProject('Creatorspace'));
await page.waitForTimeout(400);
await page.screenshot({path:'public/woltspace/assets/workflow.png'});
await page.evaluate(()=>{closeProject();showProjects();toggleTerminal({preventDefault(){}});});
await page.waitForTimeout(300);
await page.locator('.connectors-toggle').click();
await page.waitForTimeout(350);
await page.screenshot({path:'public/woltspace/assets/terminal.png'});
await browser.close();
